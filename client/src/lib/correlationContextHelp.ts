export function correlationStatusHelp(status: CorrelationContextItem["status"]) {
  if (status === "aligned") return "متوافق: حركة الأصل المرتبط تتماشى مع العلاقة المتوقعة له في هذه اللقطة السوقية.";
  if (status === "divergent") return "متعارض: حركة الأصل المرتبط لا تتماشى مع العلاقة المتوقعة له في هذه اللقطة، لذا ينبغي التعامل مع السياق بحذر.";
  if (status === "context_only") return "سياقي: هذا الأصل يقدّم خلفية عن السوق أو السيولة، ولا يدخل في مقارنة اتجاهية مباشرة مع الرمز محل التحليل.";
  return "غير حاسم: لا تتوفر حركة قابلة للمقارنة أو بيانات تغير كافية لهذا الأصل في هذه اللقطة.";
}
